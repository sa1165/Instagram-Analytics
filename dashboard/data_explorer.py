"""Data Explorer and Export Module.
Provides interactive granular filtering, custom column selection,
sorting, pagination, and multi-format download capabilities (Cleaned CSV and Filtered CSV).
"""

import streamlit as st
import pandas as pd


def render_data_explorer(df):
    st.markdown("## 🔍 Data Explorer & Dataset Export")
    st.markdown("Search, sort, slice, and inspect post-level granular records. Download custom filtered slices or export the full cleaned data artifact.")

    if df.empty:
        st.warning("⚠️ No records to display under active filters.")
        return

    # 1. Quick Filters and Search
    st.markdown("### 🔎 Granular Search & Column Selection")
    c1, c2 = st.columns([2, 1])

    with c1:
        search_query = st.text_input("Search by Post ID (e.g. 'IG0000001')", placeholder="Enter Post ID...")

    # Filter by search query if supplied
    display_df = df.copy()
    if search_query:
        display_df = display_df[display_df["post_id"].astype(str).str.contains(search_query.strip(), case=False, na=False)]

    # Column selector
    all_columns = list(display_df.columns)
    default_columns = [
        "post_id", "account_id", "account_type", "media_type", "content_category",
        "traffic_source", "has_call_to_action", "post_date", "post_hour",
        "likes", "comments", "shares", "saves", "reach", "impressions",
        "calculated_engagement_rate", "performance_bucket_label"
    ]
    # Filter default columns to ensure presence
    valid_defaults = [c for c in default_columns if c in all_columns]

    with c2:
        selected_columns = st.multiselect(
            "Select Columns to Display",
            options=all_columns,
            default=valid_defaults
        )

    if not selected_columns:
        selected_columns = valid_defaults

    # Sorting
    c3, c4, c5 = st.columns([2, 1, 1])
    with c3:
        sort_col = st.selectbox("Sort By Column", options=selected_columns, index=selected_columns.index("likes") if "likes" in selected_columns else 0)
    with c4:
        sort_order = st.radio("Order", ["Descending", "Ascending"], horizontal=True)

    sorted_df = display_df[selected_columns].sort_values(
        by=sort_col,
        ascending=(sort_order == "Ascending")
    )

    # 2. Pagination controls
    total_matching_rows = len(sorted_df)
    page_size = 50
    total_pages = max(1, (total_matching_rows + page_size - 1) // page_size)

    with c5:
        page_num = st.number_input("Page", min_value=1, max_value=total_pages, value=1, step=1)

    start_idx = (page_num - 1) * page_size
    end_idx = min(start_idx + page_size, total_matching_rows)

    st.caption(f"Displaying rows {start_idx + 1:,} to {end_idx:,} of {total_matching_rows:,} total matching records.")
    st.dataframe(sorted_df.iloc[start_idx:end_idx], use_container_width=True)

    # 3. Export Section
    st.markdown("---")
    st.markdown("### 📥 Data Export Options")
    col_dl1, col_dl2 = st.columns(2)

    with col_dl1:
        # Download filtered CSV
        filtered_csv_bytes = sorted_df.to_csv(index=False).encode("utf-8")
        st.download_button(
            label=f"⬇️ Download Filtered Subset ({len(sorted_df):,} rows CSV)",
            data=filtered_csv_bytes,
            file_name="instagram_filtered_subset.csv",
            mime="text/csv",
            help="Download the filtered records currently selected in the dashboard."
        )

    with col_dl2:
        # Full cleaned dataset download link
        try:
            with open("data/processed/cleaned_data.csv", "rb") as f:
                full_cleaned_bytes = f.read()
            st.download_button(
                label="⬇️ Download Complete Cleaned Dataset (29,999 rows CSV)",
                data=full_cleaned_bytes,
                file_name="instagram_cleaned_data_master.csv",
                mime="text/csv",
                help="Download the complete engineered master dataset generated by the ETL pipeline."
            )
        except Exception as e:
            st.info("Run ETL pipeline to generate master cleaned CSV file for download.")

